-- 1. Tabla de Clientes y Contratos
CREATE TABLE IF NOT EXISTS clientes (
    id TEXT PRIMARY KEY,
    nombre TEXT NOT NULL,
    template_type TEXT NOT NULL DEFAULT 'nabors',
    ultimo_certificado BIGINT NOT NULL DEFAULT 0,
    contrato_nro TEXT DEFAULT '',
    servicio_defecto TEXT DEFAULT '',
    oc_np_defecto TEXT DEFAULT '',
    sucursal TEXT DEFAULT 'Sucursal NQN y Valle',
    direccion TEXT DEFAULT 'Industriales Neuquinos 2920, PIN',
    telefono TEXT DEFAULT 'T:[0299] 4782500',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 2. Lista de Precios y Tarifario
CREATE TABLE IF NOT EXISTS lista_precios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id TEXT NOT NULL,
    equipo TEXT NOT NULL,
    marca TEXT DEFAULT '-',
    modelo TEXT DEFAULT '-',
    interno TEXT DEFAULT '-',
    tarifa_diaria NUMERIC DEFAULT 0.0,
    tarifa_semanal NUMERIC DEFAULT 0.0,
    tarifa_mensual NUMERIC DEFAULT 0.0,
    modalidad_defecto TEXT DEFAULT 'diario',
    moneda TEXT DEFAULT 'USD',
    observaciones TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 3. Historial de Certificados Generados
CREATE TABLE IF NOT EXISTS certificados_historial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente TEXT NOT NULL,
    certificado_nro TEXT NOT NULL,
    fecha_emision TEXT NOT NULL,
    servicio_obra TEXT DEFAULT '',
    oc_np TEXT DEFAULT '',
    total_monto NUMERIC DEFAULT 0.0,
    moneda TEXT DEFAULT 'USD',
    usuario TEXT NOT NULL,
    items_count INTEGER DEFAULT 0,
    metadata_json TEXT DEFAULT '{}',
    items_json TEXT DEFAULT '[]',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 4. Firmas Digitales de Usuarios
CREATE TABLE IF NOT EXISTS firmas_usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario TEXT NOT NULL,
    nombre_firmante TEXT NOT NULL,
    cargo TEXT NOT NULL,
    alias TEXT NOT NULL,
    firma_png_base64 TEXT NOT NULL,
    is_default INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- Desactivar Row Level Security (RLS) para permitir acceso vía service_role / anon_key configurada en Streamlit
ALTER TABLE clientes DISABLE ROW LEVEL SECURITY;
ALTER TABLE lista_precios DISABLE ROW LEVEL SECURITY;
ALTER TABLE certificados_historial DISABLE ROW LEVEL SECURITY;
ALTER TABLE firmas_usuarios DISABLE ROW LEVEL SECURITY;

